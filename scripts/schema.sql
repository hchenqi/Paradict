create function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = pg_temp
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger entries_set_updated_at before update on public.entries
for each row execute function public.set_updated_at();


