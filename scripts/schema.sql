create function public.create_user()
returns trigger
language plpgsql
security definer
SET search_path = ''
as $$
begin
  insert into public.users (id, username) values (new.id, new.raw_user_meta_data ->> 'username');
  return new;
end;
$$;

revoke execute on function public.create_user() from public;

create trigger on_auth_user_created after insert on auth.users
for each row execute function public.create_user();


create function public.update_user_role(user_id uuid, user_role text)
returns void
language plpgsql
security definer
SET search_path = ''
as $$
begin
  if not exists (select 1 from public.users where id = (select auth.uid()) and role = 'admin') then
    raise exception 'not authorized';
  end if;

  if user_role not in ('member', 'editor', 'admin') then
    raise exception 'invalid role';
  end if;

  update public.users set role = user_role where id = user_id;

  if not found then
    raise exception 'user not found';
  end if;
end;
$$;

revoke execute on function public.update_user_role(uuid, text) from public;
grant execute on function public.update_user_role(uuid, text) to authenticated;


create function public.delete_own_user()
returns void
language sql
security definer
SET search_path = ''
as $$
  delete from auth.users where id = (select auth.uid());
$$;

revoke execute on function public.delete_own_user() from public;
grant execute on function public.delete_own_user() to authenticated;
