create function public.search(query text, language_list bigint[], result_limit integer)
returns table (
  id bigint,
  concept bigint,
  lang bigint,
  expr text,
  score real
)
language plpgsql
stable
security invoker
set search_path = extensions
as $$
#variable_conflict use_column
begin
  if nullif(trim(query), '') is null then
    raise exception 'query must not be empty';
  end if;

  if char_length(query) > 100 then
    raise exception 'query must not exceed 100 characters';
  end if;

  if cardinality(language_list) > 20 then
    raise exception 'language_list must not contain more than 20 languages';
  end if;

  if result_limit is null or result_limit < 1 then
    raise exception 'result_limit must be greater than 0';
  end if;

  if result_limit > 100 then
    raise exception 'result_limit must not exceed 100';
  end if;

  perform set_config('pg_trgm.word_similarity_threshold', '0.5', true);

  return query
  with matched_entries as (
    select
      e.id,
      e.concept,
      e.lang,
      similarity(query, e.expr) as score
    from public.entries e
    where query <% e.expr
    order by score desc
    limit result_limit
  ),
  candidate_concepts as (
    select
      m.concept as id,
      max(m.score) as best_score
    from matched_entries m
    group by m.concept
  )
  select
    e.*,
    m.score
  from public.entries e
  join candidate_concepts c on c.id = e.concept
  left join matched_entries m on m.id = e.id
  where e.lang = any(language_list) or exists (
    select 1
    from matched_entries me
    where me.concept = e.concept
      and me.lang = e.lang
  )
  order by c.best_score desc, e.concept asc, m.score desc nulls last;
end;
$$;

revoke execute on function public.search(text, bigint[], integer) from public;
grant execute on function public.search(text, bigint[], integer) to anon, authenticated;


create function public.explore(result_limit integer)
returns setof public.entries
language plpgsql
stable
security invoker
set search_path = ''
as $$
begin
  if result_limit is null or result_limit < 1 then
    raise exception 'result_limit must be greater than 0';
  end if;

  if result_limit > 10 then
    raise exception 'result_limit must not exceed 10';
  end if;

  return query
  with candidate_concepts as (
    select id
    from public.concepts c
    order by random()
    limit result_limit
  )
  select e.* from public.entries e
  join candidate_concepts c on c.id = e.concept;
end;
$$;

revoke execute on function public.explore(integer) from public;
grant execute on function public.explore(integer) to anon, authenticated;


-- =========================================================================
-- Users & Submissions Tables
-- =========================================================================

create table public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('member', 'editor', 'admin')),
  username text not null unique check (char_length(username) between 6 and 30 and username ~ '^[a-z0-9_]+$'),
  display_name text check (char_length(display_name) <= 50)
);

create table public.submissions (
  id bigint generated always as identity primary key,
  created_by uuid references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  payload jsonb not null check (pg_column_size(payload) <= 16 * 1024),
  review_status text not null default 'pending' check (review_status in ('pending', 'approved', 'rejected')),
  reviewed_by uuid references public.users(id) on delete set null,
  review_note jsonb,
  reviewed_at timestamptz
);

create index idx_submissions_created_by on public.submissions(created_by) where created_by is not null;
create index idx_submissions_reviewed_by on public.submissions(reviewed_by) where reviewed_by is not null;
create index idx_submissions_pending on public.submissions(created_at) where review_status = 'pending';


grant select (id, role, username, display_name) on public.users to authenticated;
grant update (username, display_name) on public.users to authenticated;
grant select, delete on public.submissions to authenticated;
grant insert (created_by, payload) on public.submissions to authenticated;
grant update (review_status, reviewed_by, review_note, reviewed_at) on public.submissions to authenticated;


alter table public.users enable row level security;
alter table public.submissions enable row level security;


