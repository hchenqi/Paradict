create table public.concepts (
  id bigint generated by default as identity primary key
);

create table public.languages (
  id bigint generated by default as identity primary key,
  iso_code text not null unique check (iso_code = lower(iso_code))
);

create table public.entries (
  id bigint generated by default as identity primary key,
  concept_id bigint not null references public.concepts(id) on delete cascade,
  language_id bigint not null references public.languages(id),
  expression text not null,
  indexed boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (concept_id, language_id, expression)
);

create index idx_entries_expression_trgm on public.entries using gin (expression extensions.gin_trgm_ops) where indexed;


grant select on public.languages, public.concepts, public.entries to anon, authenticated;
grant insert, delete on public.languages, public.concepts to authenticated;
grant update (iso_code) on public.languages to authenticated;
grant insert (concept_id, language_id, expression, indexed) on public.entries to authenticated;
grant update (expression, indexed) on public.entries to authenticated;
grant delete on public.entries to authenticated;

alter table public.concepts enable row level security;
alter table public.languages enable row level security;
alter table public.entries enable row level security;


create policy concepts_public_read on public.concepts for select
  to anon, authenticated using (true);

create policy languages_public_read on public.languages for select
  to anon, authenticated using (true);

create policy entries_public_read on public.entries for select
  to anon, authenticated using (true);


create function public.search(
  query text,
  language_list bigint[],
  result_limit integer
)
returns table (
  concept_id bigint,
  language_id bigint,
  entry_id bigint,
  expression text,
  indexed boolean
)
language plpgsql
stable
security invoker
set search_path = extensions, pg_temp
as $$
begin
  if nullif(trim(query), '') is null then
    raise exception 'query must not be empty';
  end if;

  if char_length(query) > 100 then
    raise exception 'query must not exceed 100 characters';
  end if;

  if language_list is null or cardinality(language_list) = 0 then
    raise exception 'language_list must not be empty';
  end if;

  if cardinality(language_list) > 20 then
    raise exception 'language_list must not contain more than 20 languages';
  end if;

  if result_limit is null or result_limit < 1 then
    raise exception 'result_limit must be greater than 0';
  end if;

  if result_limit > 100 then
    raise exception 'result_limit must not exceed 100';
  end if;

  return query
  with candidate_concepts as (
    select
      e.concept_id as id,
      max(similarity(e.expression, query)) as best_score
    from public.entries e
    where e.indexed
      and e.expression % query
      and e.language_id = any(language_list)
    group by e.concept_id
    order by best_score desc
    limit result_limit
  )
  select
    e.concept_id,
    e.language_id,
    e.id as entry_id,
    e.expression,
    e.indexed
  from public.entries e
  join candidate_concepts c on c.id = e.concept_id
  where e.language_id = any(language_list)
  order by c.best_score desc;
end;
$$;

revoke execute on function public.search(text, bigint[], integer) from public;
grant execute on function public.search(text, bigint[], integer) to anon, authenticated;


create function public.explore(
  result_limit integer
)
returns table (
  concept_id bigint,
  language_id bigint,
  entry_id bigint,
  expression text,
  indexed boolean
)
language plpgsql
stable
security invoker
set search_path = pg_temp
as $$
begin
  if result_limit is null or result_limit < 1 then
    raise exception 'result_limit must be greater than 0';
  end if;

  if result_limit > 20 then
    raise exception 'result_limit must not exceed 20';
  end if;

  return query
  with candidate_concepts as (
    select id
    from public.concepts c
    order by random()
    limit result_limit
  )
  select
    e.concept_id,
    e.language_id,
    e.id as entry_id,
    e.expression,
    e.indexed
  from public.entries e
  join candidate_concepts c on c.id = e.concept_id;
end;
$$;

revoke execute on function public.explore(integer) from public;
grant execute on function public.explore(integer) to anon, authenticated;


-- =========================================================================
-- Users & Submissions Tables
-- =========================================================================

create table public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('member', 'editor', 'admin')),
  username text not null unique check (char_length(username) between 6 and 30 and username ~ '^[a-z0-9_]+$'),
  display_name text check (char_length(display_name) <= 50),
);

create table public.submissions (
  id bigint generated by default as identity primary key,
  created_by uuid references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  payload jsonb not null check (pg_column_size(payload) <= 16 * 1024),
  review_status text not null default 'pending' check (review_status in ('pending', 'approved', 'rejected')),
  reviewed_by uuid references public.users(id) on delete set null,
  review_note text check (char_length(review_note) <= 300),
  reviewed_at timestamptz,
  check (review_status = 'pending' or (reviewed_by is not null and reviewed_at is not null))
);

create index idx_submissions_created_by on public.submissions(created_by);
create index idx_submissions_reviewed_by on public.submissions(reviewed_by);
create index idx_submissions_pending on public.submissions(created_at) where review_status = 'pending';


grant select (id, role, username, display_name) on public.users to authenticated;
grant update (username, display_name) on public.users to authenticated;
grant select, delete on public.submissions to authenticated;
grant insert (created_by, payload) on public.submissions to authenticated;
grant update (review_status, reviewed_by, review_note, reviewed_at) on public.submissions to authenticated;

alter table public.users enable row level security;
alter table public.submissions enable row level security;


create policy users_member_read on public.users for select
  to authenticated using (true);

create policy users_own_update on public.users for update
  to authenticated using ((select auth.uid()) = id) with check ((select auth.uid()) = id);


create policy submissions_member_select on public.submissions for select
  to authenticated using (true);

create policy submissions_own_insert on public.submissions for insert
  to authenticated with check ((select auth.uid()) = created_by);

create policy submissions_editor_update on public.submissions for update
  to authenticated using (exists (select 1 from public.users actor where actor.id = (select auth.uid()) and actor.role in ('editor', 'admin')));

create policy submissions_own_admin_delete on public.submissions for delete
  to authenticated using (((select auth.uid()) = created_by and review_status in ('pending', 'rejected')) or exists (select 1 from public.users actor where actor.id = (select auth.uid()) and actor.role = 'admin'));


